import { writeFileSync } from 'node:fs';

const out = new URL('../tgcloud/lib/countries.js', import.meta.url);

const SOURCE = 'https://raw.githubusercontent.com/dr5hn/countries-states-cities-database/master/json/countries.json';
const all = await (await fetch(SOURCE)).json();

const list = all
.filter(c => c.region && c.region !== 'Polar')
.map(c => [c.iso2, c.name, c.emoji, c.region, c.subregion])          // code, name, flag emoji
.sort((a, b) => a[1].localeCompare(b[1]));

const body = list.map(c => `  ${JSON.stringify(c)},`).join('\n');
writeFileSync(out, `// generated by scripts/gen-countries.mjs, do not edit\nexport const COUNTRIES = [\n${body}\n];\n`);

console.log(list.length, 'countries');